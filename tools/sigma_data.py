"""D2Sigma's own tables as compiled-in plugin data (docs/plugin-spec.md, "Compiled-in Sigma tables"):

  plugin/src/mxl_requirements.h  requirements.bin (33 rows x 44 bytes): the boolean condition trees that gate NPC services
  plugin/src/mxl_dungeons.h      levels.bin extension fields +0x151..+0x15f except the goblin chance: dungeon lockout
                                 (lock time, lock group), entry requirements (minimum difficulty, level per difficulty,
                                 class lock), the quest each level needs (leveldefs.bin QuestFlagEx) and the fields
                                 whose meaning is not established (kept raw)
  plugin/src/mxl_goblins.h       GoblinChance per level (levels +0x15c) and the monstats3 treasure goblin rows
  plugin/src/mxl_monster_looks.h monstats3 rank bits, NameColor, automap fields and spawn overlays per monster

Sources are the compiled tables in extract/mxl (raw bytes: the sigma decode has no names for these fields); ids go
through work/named/idmap.json: levels and monsters are Median row numbers in the sources and D2R ids in the output.
Quest ids, bits, classes and item codes need no mapping (Median keeps the vanilla quest array and its item codes).

Usage: python tools/sigma_data.py   (after mxl_names.py; build.py runs it after cube_tables.py)
"""
import json
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BINS = ROOT / "extract" / "mxl" / "data" / "global" / "excel"
IDMAP = ROOT / "work" / "named" / "idmap.json"
SRC = ROOT / "plugin" / "src"
MODXL = ROOT / "work" / "mod" / "data" / "global" / "excel"

REQ_ROW = 44
LEVEL_ROW = 0x220
LEVELDEF_ROW = 0x9c    # leveldefs.bin: QuestFlag (+0) and QuestFlagEx (+4) first; D2Sigma's table at TxtRecords +0xc60
MONSTATS3_ROW = 44
GOBLIN_FLAG = 0x400    # monstats3 flag word (+0): goblin candidate (D2Goblins 0x65be0)
RAINBOW_FLAG = 0x1000  # ... only the Halloween rainbow goblin
HEADER = "// Generated by tools/sigma_data.py; do not edit."


def table(name: str, row: int) -> list[bytes]:
    b = (BINS / f"{name}.bin").read_bytes()
    n = struct.unpack_from("<I", b)[0]
    if len(b) != 4 + n * row:
        raise SystemExit(f"{name}.bin: {len(b)} bytes is not {n} rows of {row}")
    return [b[4 + i * row:4 + (i + 1) * row] for i in range(n)]


def ids(idmap: dict, entity: str) -> dict[int, int]:
    return {e["row"]: e["id"] for e in idmap[entity]}


def requirements() -> tuple[str, str]:
    rows = table("requirements", REQ_ROW)
    # types the plugin evaluates (docs/subsystems/quests-requirements.md): 1 OR, 2 AND, 9 quest bit set, 30 class ==,
    # 35 does not hold item code, 36 constant false
    supported = {0, 1, 2, 9, 30, 35, 36}
    lines = [HEADER, "#pragma once", "", "#include <cstdint>", "", "namespace mxl_requirements {", "",
             "// D2Sigma's requirements table (D2Requirements.cpp). type: 1 OR, 2 AND (children = row indexes, 0 = unused),",
             "// 9 quest bit set (a = quest id, b = bit, c = difficulty, -1 = the game's), 30 player class == a,",
             "// 35 player does NOT hold an item with the 4-character code, 36 always false. Row 0 and negative",
             "// indexes mean \"no requirement\". Quest ids, classes and item codes are the same in D2R.",
             "inline constexpr int32_t MaxChildren = 10;", "struct Row {", "\tint32_t type;", "\tint32_t a;", "\tint32_t b;",
             "\tint32_t c;", "\tint32_t child[MaxChildren];", "\tchar code[5];  // type 35 only (NUL-terminated)", "};",
             f"inline constexpr int32_t RowCount = {len(rows)};", "inline constexpr Row Rows[RowCount] = {"]
    unsupported = []
    for i, r in enumerate(rows):
        v = struct.unpack("<11i", r)
        t = v[0]
        if t not in supported:
            unsupported.append((i, t))
        a = b = c = 0
        kids = [0] * 10
        code = ""
        if t in (1, 2):
            kids = list(v[1:11])
        elif t == 35:
            code = r[4:8].decode("latin-1")
        else:
            a, b, c = v[1:4]
        note = {1: "OR", 2: "AND", 9: "quest bit", 30: "class", 35: "no item", 36: "false", 0: "none"}.get(t, f"type {t}")
        lines.append(f"    {{{t}, {a}, {b}, {c}, {{{', '.join(map(str, kids))}}}, \"{code}\"}},  // {i}: {note}")
    lines += ["};", "", "}  // namespace mxl_requirements", ""]
    msg = f"requirements: {len(rows)} rows -> plugin/src/mxl_requirements.h"
    if unsupported:
        msg += f"; WARNING unsupported condition types (row, type): {unsupported}"
    return "\n".join(lines), msg


def levels_and_goblins(idmap: dict) -> tuple[str, str, str]:
    levels = ids(idmap, "levels")
    mons = ids(idmap, "monstats")
    mnames = {e["row"]: e["name"] for e in idmap["monstats"]}
    lnames = {e["row"]: e["name"] for e in idmap["levels"]}
    lrows = table("levels", LEVEL_ROW)
    if len(lrows) != len(levels):
        raise SystemExit(f"levels.bin has {len(lrows)} rows, idmap {len(levels)}")

    # D2Sigma's warp test (0x5d810) reads QuestFlagEx (+4) of the destination's leveldefs row; row = Median level row
    ldefs = table("leveldefs", LEVELDEF_ROW)
    if len(ldefs) != len(lrows):
        raise SystemExit(f"leveldefs.bin has {len(ldefs)} rows, levels.bin {len(lrows)}")
    dungeon, chances = [], []
    for row, r in enumerate(lrows):
        lid = levels[row]
        min_diff = r[0x151]
        unk152 = r[0x152]
        lock = struct.unpack_from("<H", r, 0x153)[0]  # +0x154 is its high byte (the docs list it as a separate field)
        unk155 = r[0x155]
        unk156 = struct.unpack_from("<H", r, 0x156)[0]
        req = (r[0x158], r[0x159], r[0x15a])
        unk15b = r[0x15b]
        chance = struct.unpack_from("<H", r, 0x15c)[0]
        class_lock = r[0x15e]
        group = r[0x15f]
        if chance:
            chances.append((lid, chance, lnames[row], struct.unpack_from("<HHH", r, 0x16)))
        quest_lock = struct.unpack_from("<I", ldefs[row], 4)[0]
        if quest_lock > 255:
            raise SystemExit(f"leveldefs row {row}: quest id {quest_lock} does not fit a byte")
        if any((min_diff, unk152, lock, unk155, unk156, *req, unk15b, class_lock, group, quest_lock)):
            dungeon.append((lid, lock, group, min_diff, req, class_lock, unk152, unk155, unk156, unk15b, quest_lock,
                            lnames[row]))

    out = [HEADER, "#pragma once", "", "#include <cstdint>", "", "namespace mxl_dungeons {", "",
           "// levels.bin extension fields +0x151..+0x15f (D2Dungeon.cpp 0x5cee0 / 0x5d9d0; docs/subsystems/ubers-events.md",
           "// section 3), one entry per level (D2R id) with any of them set. Established: lockSeconds (+0x153, u16; the",
           "// level seals this long after a portal into it is used; 0 = no clock), lockGroup (+0x15f; levels sharing a",
           "// non-zero group lock together), minDifficulty (+0x151: 0 Normal, 1 Nightmare, 2 Hell), levelReq per",
           "// difficulty (+0x158..+0x15a, player level), classLock (+0x15e: 0 none, else only class value - 1 may enter).",
           "// Raw, meaning not established: unk152 (+0x152), unk155 (+0x155: set on harder areas), portalObject",
           "// (+0x156 u16, 585 only on level 247 = the rainbow portal; a Median objects row, not remapped), unk15b",
           "// (+0x15b). questLock is QuestFlagEx of leveldefs.bin (+4; 0 = none): D2Sigma's warp test refuses the level",
           "// unless the player's record of that quest holds bit 1, 0, 0xe or 0xf. The goblin chance (+0x15c) is in",
           "// mxl_goblins.h.",
           "struct Entry {", "\tint32_t level;         // D2R level id", "\tuint16_t lockSeconds;", "\tuint8_t lockGroup;",
           "\tuint8_t minDifficulty;", "\tuint8_t levelReq[3];   // Normal, Nightmare, Hell", "\tuint8_t classLock;",
           "\tuint8_t unk152;", "\tuint8_t unk155;", "\tuint16_t portalObject;", "\tuint8_t unk15b;", "\tuint8_t questLock;", "};",
           f"inline constexpr int32_t EntryCount = {len(dungeon)};", "inline constexpr Entry Entries[EntryCount] = {"]
    for lid, lock, group, md, req, cl, u152, u155, u156, u15b, ql, name in dungeon:
        out.append(f"    {{{lid}, {lock}, {group}, {md}, {{{req[0]}, {req[1]}, {req[2]}}}, {cl}, {u152}, {u155}, {u156}, "
                   f"{u15b}, {ql}}},  // {name}")
    out += ["};", "", "}  // namespace mxl_dungeons", ""]

    m3 = table("monstats3", MONSTATS3_ROW)
    # display names of the goblin rows: the migrated monstats.txt (txt_migrate.py runs earlier) holds each monster's
    # NameStr resolved to its text; the server's "<name> appears!" line uses it
    mod_ms = MODXL / "monstats.txt"
    if not mod_ms.exists():
        raise SystemExit(f"{mod_ms} missing: run tools/txt_migrate.py first")
    ml = mod_ms.read_text("utf-8").splitlines()
    mh = ml[0].split("	")
    i_id, i_name = mh.index("Id"), mh.index("NameStr")
    import strings_ns  # NameStr is a string key (`medianxl:<key>` for Median-only names): the client shows its text
    texts = strings_ns.effective_texts()
    name_of = {}
    for line in ml[1:]:
        c = line.split("	")
        if len(c) > i_name:
            key = strings_ns.bare(c[i_name])
            name_of[c[i_id]] = texts.get(key, key)
    gob = []
    for row, r in enumerate(m3):
        flags = struct.unpack_from("<I", r)[0]
        if not flags & (GOBLIN_FLAG | RAINBOW_FLAG):
            continue
        rarity, lo, hi, restrict = struct.unpack_from("<HHHH", r, 0x17)
        if restrict == 0xffff:
            rl = -1
        elif restrict in levels:
            rl = levels[restrict]
        else:
            raise SystemExit(f"monstats3 row {row}: level restrict {restrict} is not a level row")
        gob.append((mons[row], flags, rarity, lo, hi, rl, mnames[row], name_of.get(mnames[row]) or mnames[row]))

    g = [HEADER, "#pragma once", "", "#include <cstdint>", "", "namespace mxl_goblins {", "",
         "// Treasure goblins (D2Goblins.cpp; docs/subsystems/ubers-events.md section 4).",
         "// Chance: levels.bin +0x15c (u16, per level, D2R id), rolled against 1024 after a reduction of 10% per player",
         "// beyond the first (0x66070: chance - chance * (10 * players - 10) / 100, at least 1). monLevel = levels.bin",
         "// +0x16 + 2 * difficulty (u16 x3, what 0x65de0 compares with the goblin level bounds).",
         "struct Chance {", "\tint32_t level;", "\tuint16_t chance;", "\tuint16_t monLevel[3];", "};",
         f"inline constexpr int32_t ChanceCount = {len(chances)};", "inline constexpr Chance Chances[ChanceCount] = {"]
    g += [f"    {{{lid}, {c}, {{{ml[0]}, {ml[1]}, {ml[2]}}}}},  // {n}" for lid, c, n, ml in chances]
    g += ["};", "",
          "// Candidates: monstats3 rows (D2R monster id) with flag bit 0x400, all fields from the row. Candidate when the",
          "// area's monster level (levels record, per difficulty; not in this table) is within [minLevel, maxLevel] (0 =",
          "// no bound) and levelRestrict is -1 or the area (D2R level id); rainbow (flag 0x1000) is Halloween only. Each",
          "// row is drawn `rarity` times (monstats3 +0x17, u16; a plain weight, confirmed from 0x65de0).",
          "// flags is the whole monstats3 +0 word; bits other than 0x400 / 0x1000 are not understood.",
          "inline constexpr uint32_t FlagGoblin = 0x400;", "inline constexpr uint32_t FlagRainbow = 0x1000;",
          "struct Goblin {", "\tint32_t monster;       // D2R monstats id", "\tuint32_t flags;", "\tuint16_t rarity;",
          "\tuint16_t minLevel;", "\tuint16_t maxLevel;", "\tint32_t levelRestrict; // D2R level id, -1 = any",
          "\tconst char* name;     // monstats NameStr text, what the client shows as the unit's name", "};",
          f"inline constexpr int32_t GoblinCount = {len(gob)};", "inline constexpr Goblin Goblins[GoblinCount] = {"]
    g += [f"    {{{m}, 0x{f:x}, {ra}, {lo}, {hi}, {rl}, {json.dumps(dn)}}},  // {n}" for m, f, ra, lo, hi, rl, n, dn in gob]
    towns = [levels[row] for row, r in enumerate(lrows) if r[0x14b]]
    nokill = [mons[row] for row, r in enumerate(m3) if r[0x20]] or [-1]
    g += ["};", "",
          "// Monsters whose kills do not count as \"the player just killed something\" (monstats3 +0x20, the loader's",
          "// NoKillTimestampUpdate; D2Achievements.cpp 0x49c40 stores the player's last-kill frame only when it is 0).",
          f"inline constexpr int32_t NoKillCount = {len(nokill)};",
          f"inline constexpr int32_t TownCount = {len(towns)};",
          "// Levels with the town flag (levels.bin +0x14b, D2R ids): no goblins while a player stands in one.",
          "inline constexpr int32_t Towns[TownCount] = {" + ", ".join(str(t) for t in towns) + "};",
          "inline constexpr int32_t NoKill[NoKillCount] = {" + ", ".join(str(m) for m in nokill) + "};", "",
          "}  // namespace mxl_goblins", ""]
    msg = (f"dungeons: {len(dungeon)} levels -> plugin/src/mxl_dungeons.h; goblins: {len(chances)} level chances, "
           f"{len(gob)} monsters -> plugin/src/mxl_goblins.h")
    return "\n".join(out), "\n".join(g), msg


LOOK_RANK = 0xf8     # monstats3 Flags: Elite 0x08, Veteran 0x10, Uber 0x20, Heroic 0x40, Boss 0x80 (name colour ranks)
LOOK_AUTOMAP = 0x06  # Automap 0x02, AutomapShowName 0x04


def monster_looks(idmap: dict) -> tuple[str, str]:
    """monstats3 name colour, automap and spawn overlay fields of every monster that sets one of them."""
    mons = ids(idmap, "monstats")
    mnames = {e["row"]: e["name"] for e in idmap["monstats"]}
    ovl = ids(idmap, "overlay")
    rows = []
    for row, r in enumerate(table("monstats3", MONSTATS3_ROW)):
        flags = struct.unpack_from("<H", r)[0]
        name_color, auto_name, auto_vec = r[2], r[3], r[4]
        overlays = list(struct.unpack_from("<4h", r, 6))  # Overlay1/2, BossOverlay1/2; -1 = none
        for i, o in enumerate(overlays):
            if o >= 0:
                if o not in ovl:
                    raise SystemExit(f"monstats3 row {row}: overlay {o} is not an overlay row")
                overlays[i] = ovl[o]
        otype = r[0x1f]
        if not (flags & (LOOK_RANK | LOOK_AUTOMAP) or name_color or any(o >= 0 for o in overlays)):
            continue
        rows.append((mons[row], flags & (LOOK_RANK | LOOK_AUTOMAP), name_color, auto_name, auto_vec, otype, overlays,
                     mnames[row]))
    rows.sort()
    out = [HEADER, "#pragma once", "", "#include <cstdint>", "", "namespace mxl_looks {", "",
           "// monstats3 fields that change how a monster looks (FUN_1008b570 name colour, FUN_1004b620 automap marker,",
           "// FUN_1008c3f0 spawn overlay), one row per monster (D2R id, ascending) that sets any of them.",
           "// flags: 0x02 Automap, 0x04 AutomapShowName, rank bits 0x08 Elite / 0x10 Veteran / 0x20 Uber / 0x40 Heroic /",
           "// 0x80 Boss. nameColor / automapNameColor are colour indexes (D2 text colours), automapVectorColor a palette",
           "// index. overlay[0..1] = Overlay1/2, [2..3] = BossOverlay1/2 (D2R overlay ids, -1 none): a unique or super",
           "// unique plays the boss pair, any other monster the first pair (FUN_1008c3f0). overlayType is the byte at",
           "// +0x1f, Median's last argument of its overlay call (2 with Overlay1 only, 3 with front and back); D2R's",
           "// overlay call has no such argument.",
           "inline constexpr uint16_t FlagAutomap = 0x02, FlagAutomapName = 0x04;",
           "inline constexpr uint16_t RankElite = 0x08, RankVeteran = 0x10, RankUber = 0x20, RankHeroic = 0x40, RankBoss = 0x80;",
           "struct Look {", "\tint32_t monster;", "\tuint16_t flags;", "\tuint8_t nameColor;", "\tuint8_t automapNameColor;",
           "\tuint8_t automapVectorColor;", "\tuint8_t overlayType;", "\tint16_t overlay[4];", "};",
           f"inline constexpr int32_t LookCount = {len(rows)};", "inline constexpr Look Looks[LookCount] = {"]
    for m, f, nc, an, av, ot, ov, n in rows:
        out.append(f"    {{{m}, 0x{f:x}, {nc}, {an}, {av}, {ot}, {{{ov[0]}, {ov[1]}, {ov[2]}, {ov[3]}}}}},  // {n}")
    out += ["};", "", "}  // namespace mxl_looks", ""]
    nover = sum(1 for r in rows if any(o >= 0 for o in r[6]))
    return "\n".join(out), (f"monster looks: {len(rows)} monsters ({sum(1 for r in rows if r[1] & LOOK_RANK)} ranked, "
                            f"{sum(1 for r in rows if r[1] & LOOK_AUTOMAP)} automap, {nover} spawn overlays) -> "
                            f"plugin/src/mxl_monster_looks.h")


SKILLS2_ROW = 66
SKILL_BASE_SYNERGY = 0x2d  # skills2 byte: built-in level/energy damage bonus (D2SkillCalc 0x100a6c70)
SKILL_STATIC_DAMAGE = 0x2e  # skills2 byte: no mastery bonus (D2SkillCalc 0x100a5d00 and the other three)
STAT_BASE_SYNERGY = 485     # Median itemstatcost row the BaseSynergy percent reads (/ 10, capped at 100)


def skill_flags(idmap: dict) -> tuple[str, str]:
    """skills2 BaseSynergy / StaticDamage bytes per skill, and the stat id BaseSynergy reads."""
    skills = ids(idmap, "skills")
    snames = {e["row"]: e["name"] for e in idmap["skills"]}
    stats = ids(idmap, "itemstatcost")
    rows = []
    for row, r in enumerate(table("skills2", SKILLS2_ROW)):
        flags = (1 if r[SKILL_BASE_SYNERGY] else 0) | (2 if r[SKILL_STATIC_DAMAGE] else 0)
        if flags:
            rows.append((skills[row], flags, snames[row]))
    rows.sort()
    out = [HEADER, "#pragma once", "", "#include <cstdint>", "", "namespace mxl_skill_flags {", "",
           "// skills2 bytes +0x2d (BaseSynergy: the skill's damage gets a level- and energy-based percent) and +0x2e",
           "// (StaticDamage: mastery stats do not raise it), one row per skill (D2R id, ascending) that sets either.",
           "inline constexpr uint8_t BaseSynergy = 1, StaticDamage = 2;",
           "struct Flag {", "\tint32_t skill;", "\tuint8_t flags;", "};",
           f"inline constexpr int32_t FlagCount = {len(rows)};", "inline constexpr Flag Flags[FlagCount] = {"]
    for sid, f, n in rows:
        out.append(f"    {{{sid}, {f}}},  // {n}")
    out += ["};", "",
            f"// Median itemstatcost row {STAT_BASE_SYNERGY} (migrated id), read by the BaseSynergy percent.",
            f"inline constexpr int32_t StatBaseSynergy = {stats[STAT_BASE_SYNERGY]};", "",
            "}  // namespace mxl_skill_flags", ""]
    nb = sum(1 for r in rows if r[1] & 1)
    ns = sum(1 for r in rows if r[1] & 2)
    return "\n".join(out), (f"skill flags: {nb} BaseSynergy, {ns} StaticDamage skills -> plugin/src/mxl_skill_flags.h")


def main() -> int:
    idmap = json.loads(IDMAP.read_text("utf-8"))
    req, msg = requirements()
    (SRC / "mxl_requirements.h").write_text(req, encoding="utf-8")
    print(msg)
    looks, msg = monster_looks(idmap)
    (SRC / "mxl_monster_looks.h").write_text(looks, encoding="utf-8")
    print(msg)
    flags, msg = skill_flags(idmap)
    (SRC / "mxl_skill_flags.h").write_text(flags, encoding="utf-8")
    print(msg)
    dng, gob, msg = levels_and_goblins(idmap)
    (SRC / "mxl_dungeons.h").write_text(dng, encoding="utf-8")
    (SRC / "mxl_goblins.h").write_text(gob, encoding="utf-8")
    print(msg)
    return 0


if __name__ == "__main__":
    sys.exit(main())
