"""D2Sigma's NPC menu slots and NPC actions as compiled-in plugin data (plugin/src/mxl_npc_actions.h).

Sources (extract/mxl, the compiled tables; layout in docs/subsystems/npc-hirelings.md section 1.2):
  npcext.bin      49 rows x 336 bytes; per NPC 16 menu slots of 16 bytes at +0x50: i32 requirement row (-1 = always),
                  i32 npcactions row, u16 label string id (Median), u16 prompt label (the confirmation's text), u16
                  menu id (10 = an entry of the submenu the preceding top-level slot opens), u8 weight, u8 prompt
                  confirm (1 = ask first; only Akara's respec line)
  npcactions.bin  31 rows x 52 bytes: i32 type, i32 requirement row, i32 flags, 10 x i32 values

Median string ids become D2R ids through work/mod/strings_idkeys.json (Median id -> key) and the string JSONs in
extract/d2r/93847/data/local/lng/strings (key -> D2R id): the client menu looks lines up by D2R id. Strings in the
`medianxl` namespace (docs/strings-namespace.md; idkeys value `medianxl:<key>`) have no numeric id: the id is 0 and
the full key goes into labelKey / promptKey, which the plugin resolves at run time. Re-run this after
tools/tbl2json.py changes the ids (build.py runs it after sigma_data.py). NPC class ids are the Median monstats
rows; the NPC rows go through work/named/idmap.json (vanilla NPCs map to themselves).

Usage: python tools/npc_actions_data.py [--root <repo with extract/ and work/>]
"""
import argparse
import glob
import json
import struct
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
NAMESPACE = "medianxl"  # tools/strings_ns.py
NPC_ROW = 336
ACTION_ROW = 52
SLOT_BASE = 0x50
SLOT_SIZE = 16
SLOTS = 16
NO_STRING = 5382
HEADER = "// Generated by tools/npc_actions_data.py; do not edit."


def table(bins: Path, name: str, row: int) -> list[bytes]:
    b = (bins / f"{name}.bin").read_bytes()
    n = struct.unpack_from("<I", b)[0]
    if len(b) != 4 + n * row:
        raise SystemExit(f"{name}.bin: {len(b)} bytes is not {n} rows of {row}")
    return [b[4 + i * row:4 + (i + 1) * row] for i in range(n)]


def d2r_string_ids(root: Path) -> tuple[dict[str, str], dict[str, int]]:
    idkeys = json.loads((root / "work" / "mod" / "strings_idkeys.json").read_text("utf-8"))
    by_key: dict[str, int] = {}
    # D2R's own strings/ files (the mod ships none, its overrides keep D2R's ids)
    for f in glob.glob(str(root / "extract" / "d2r" / "93847" / "data" / "local" / "lng" / "strings" / "*.json")):
        for e in json.loads(Path(f).read_text("utf-8-sig")):
            by_key.setdefault(e["Key"], e["id"])
    return idkeys, by_key


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", type=Path, default=REPO, help="repo root holding extract/ and work/ (default: this checkout)")
    ap.add_argument("--out", type=Path, default=REPO / "plugin" / "src" / "mxl_npc_actions.h")
    args = ap.parse_args()
    root = args.root
    bins = root / "extract" / "mxl" / "data" / "global" / "excel"
    idmap = json.loads((root / "work" / "named" / "idmap.json").read_text("utf-8"))
    mon = {e["row"]: e["id"] for e in idmap["monstats"]}
    idkeys, by_key = d2r_string_ids(root)

    npcs = table(bins, "npcext", NPC_ROW)
    actions = table(bins, "npcactions", ACTION_ROW)

    def d2r_label(median_id: int) -> tuple[int, str | None]:
        """(D2R string id, namespaced full key): a native string has an id and no key, a namespaced one the reverse."""
        if median_id == NO_STRING:
            return 0, None
        key = idkeys.get(str(median_id))
        if key is not None and key.startswith(NAMESPACE + ":"):
            return 0, key
        if key is None or key not in by_key:
            raise SystemExit(f"string {median_id} has no D2R id (key {key!r}); run tools/tbl2json.py first")
        return by_key[key], None

    out = [HEADER, "#pragma once", "", "#include <cstdint>", "", "namespace mxl_npc {", "",
           "// npcactions (D2Sigma's NPC action table): type, requirement row (mxl_requirements.h), flags, up to ten values.",
           "// Types used by the shipped rows: 1 compound (values = rows), 3 text page (client), 8 travel, 11-13 imbue /",
           "// sockets / personalize pages, 14 respec, 15 waypoint, 16 continue, 17 create item (value 1 = 4-character",
           "// code, 2 = quality, 3 = item level), 18 / 20 client messages.",
           "struct Action {", "\tint32_t type;", "\tint32_t requirement;", "\tint32_t flags;", "\tint32_t value[10];", "};",
           f"inline constexpr int32_t ActionCount = {len(actions)};", "inline constexpr Action Actions[ActionCount] = {"]
    for i, r in enumerate(actions):
        v = struct.unpack("<13i", r)
        out.append(f"    {{{v[0]}, {v[1]}, {v[2]}, {{{', '.join(map(str, v[3:13]))}}}}},  // {i}")
    out += ["};", ""]

    out += ["// Menu slots of the NPCs that have any. kind = npcRow * 16 + slot is what the client sends (packet 0x38 kind",
            "// 0x10 + kind). label = D2R string id of the entry text (0 = none). sub: 10 = an entry of the submenu opened",
            "// by the top-level slot before it, 0 = a top-level entry. confirm: the client asks Yes / No first, with the text",
            "// `prompt` (D2R string id, 0 = none), before it sends the kind. A string in the `medianxl` namespace has no D2R id:",
            "// label / prompt are 0 and labelKey / promptKey hold its full key (\"medianxl:<key>\"; plugin/src/strings.h StringId).",
            "struct Slot {", "\tint32_t npcRow;", "\tint32_t slot;", "\tuint16_t npcClass;", "\tint32_t requirement;",
            "\tint32_t action;", "\tuint16_t label;", "\tuint16_t sub;", "\tuint16_t prompt;",
            "\tbool confirm;", "\tconst char* labelKey;", "\tconst char* promptKey;", "};"]
    rows = []
    for n, r in enumerate(npcs):
        cls = struct.unpack_from("<i", r, 0)[0]
        if cls not in mon:
            raise SystemExit(f"npcext row {n}: monster {cls} is not in work/named/idmap.json")
        cls = mon[cls]  # vanilla NPCs map to themselves; Median-only ones get a new D2R id
        for s in range(SLOTS):
            req, act, lab, prompt, sub, _weight, confirm = struct.unpack_from("<iiHHHBB", r, SLOT_BASE + s * SLOT_SIZE)
            if act <= 0 or act >= len(actions):
                continue
            rows.append((n, s, cls, req, act, d2r_label(lab), sub, d2r_label(prompt), confirm))
    out += [f"inline constexpr int32_t SlotCount = {len(rows)};", "inline constexpr Slot Slots[SlotCount] = {"]
    def cstr(key: str | None) -> str:
        return "nullptr" if key is None else json.dumps(key)

    for n, s, cls, req, act, (lab, lab_key), sub, (prompt, prompt_key), confirm in rows:
        out.append(f"    {{{n}, {s}, {cls}, {req}, {act}, {lab}, {sub}, {prompt}, {'true' if confirm else 'false'}, "
                   f"{cstr(lab_key)}, {cstr(prompt_key)}}},")
    out += ["};", "", "}  // namespace mxl_npc", ""]
    args.out.write_text("\n".join(out), encoding="utf-8")
    print(f"npc actions: {len(actions)} actions, {len(rows)} menu slots on {len({r[2] for r in rows})} NPCs -> {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
