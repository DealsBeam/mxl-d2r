"""Median's item tables that D2R has no columns for, as compiled-in plugin data (docs/subsystems/items-xp.md):

  plugin/src/mxl_runewords.h  runeword properties 8-13: Median's runes.txt has 13 property slots (T1Code1..13), D2R's
                              record has 7, so 197 of the 237 runewords lost properties (txt_migrate overflow/runes.txt).
                              The plugin applies the lost slots after D2R's own seven (plugin/src/items_ext.cpp).

Property codes become D2R properties.txt rows, skill/monster parameters the migrated ids (the same rules as the
property slots txt_migrate writes itself: Migrator.param_kinds / remap_property_params). Each runeword is keyed by its
row in the output runes.txt (= D2R's table index, the record is 0xe8 bytes) and by the item code of its first rune,
which the plugin compares with the live record before it applies anything.

Usage: python tools/items_data.py   (after txt_migrate.py; build.py runs it after sigma_data.py)
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(Path(__file__).resolve().parent))
import txt_migrate as tm  # noqa: E402

SRC = ROOT / "plugin" / "src"
HEADER = "// Generated by tools/items_data.py; do not edit."
FIRST_EXTRA = 8  # D2R's record holds T1Code1..7
LAST_EXTRA = 13
D2R_SLOTS = 7


def number(text: str) -> int | None:
    t = text.strip()
    return int(t) if t.lstrip("-").isdigit() else None


def code32(code: str) -> str:
    """Item code as the plugin compares it: four characters, space padded, little-endian."""
    b = (code + "    ")[:4].encode("latin1")
    return f"0x{int.from_bytes(b, 'little'):08x}"


def runeword_tables(mig: "tm.Migrator") -> tuple[str, str]:
    base = tm.OUT / "data" / "global" / "excel" / "base"
    oh, orows = tm.read_tsv(base / "runes.txt")
    nh, nrows = tm.read_tsv(tm.NAMED / "runes.txt")
    orows = [r for r in orows if tm.is_record(r)]
    nrows = [r for r in nrows if tm.is_record(r)]
    if [r[0] for r in orows] != [r[0] for r in nrows]:
        raise SystemExit("runes.txt: the output rows are not Median's rows in Median's order; row index cannot be used")
    props = mig.row_ids("properties")
    kinds = mig.param_kinds()
    ids = {"skill": mig.median_ids("skills"), "monster": mig.median_ids("monstats")}
    first_rune = nh.index("Rune1")

    skipped: list[str] = []
    out = []
    for row, r in enumerate(nrows):
        slots = []
        for k in range(FIRST_EXTRA, LAST_EXTRA + 1):
            code = r[nh.index(f"T1Code{k}")].strip()
            if not code:
                continue
            par, lo, hi = (number(r[nh.index(f"T1{c}{k}")]) for c in ("Param", "Min", "Max"))
            pid = props.get(code, -1)
            if pid < 0 or lo is None or hi is None or (r[nh.index(f"T1Param{k}")].strip() and par is None):
                skipped.append(f"{r[0]} slot {k} {code}")
                continue
            par = 0 if par is None else par
            kind = kinds.get(code)
            if kind == "skill":
                par = ids["skill"].get(par, par)
            elif kind == "monster":
                par = ids["monster"].get(par, par)
            elif kind == "skill-range":
                lo, hi = ids["skill"].get(lo, lo), ids["skill"].get(hi, hi)
            slots.append((pid, par, lo, hi, code))
        if not slots:
            continue
        if len(slots) > LAST_EXTRA - D2R_SLOTS:
            raise SystemExit(f"{r[0]}: {len(slots)} extra properties")
        rune = r[first_rune].strip()
        out.append((row, r[0], rune, slots))

    n_extra = LAST_EXTRA - D2R_SLOTS
    lines = [HEADER, "#pragma once", "", "#include <cstdint>", "", "namespace mxl_runewords {", "",
             "// Median's runeword properties 8-13 (D2R's runes.txt record holds seven). row = row of runes.txt in the",
             "// mod (D2R's table index); rune1 = item code of the first rune (4 characters, little-endian), checked",
             "// against the live record before anything is applied.",
             "// Properties: properties.txt row, param, min, max (prop -1: unused slot).",
             "struct Prop {", "\tint32_t prop, param, min, max;", "};",
             f"inline constexpr int32_t ExtraSlots = {n_extra};",
             f"inline constexpr int32_t RowCount = {len(nrows)};  // rows of runes.txt",
             "struct Extra {", "\tint32_t row;", "\tuint32_t rune1;", "\tProp props[ExtraSlots];", "};",
             "inline constexpr Extra Extras[] = {"]
    for row, name, rune, slots in out:
        cells = [f"{{{p}, {a}, {b}, {c}}}  /* {code} */" for p, a, b, c, code in slots]
        cells += ["{-1, 0, 0, 0}"] * (n_extra - len(slots))
        lines.append(f"    {{{row}, {code32(rune)}, {{{', '.join(cells)}}}}},  // {name}: {rune}")
    lines += ["};", f"inline constexpr int32_t ExtraCount = {len(out)};", "", "}  // namespace mxl_runewords", ""]
    total = sum(len(s) for _, _, _, s in out)
    msg = f"runewords: {len(out)} of {len(nrows)} with properties 8-13 ({total} properties) -> plugin/src/mxl_runewords.h"
    if skipped:
        msg += f"; WARNING skipped {len(skipped)}: {skipped[:4]}"
    if any(not rune for _, _, rune, _ in out):
        msg += "; WARNING a runeword without a first rune"
    return "\n".join(lines), msg


def main() -> int:
    mig = tm.Migrator()
    text, msg = runeword_tables(mig)
    (SRC / "mxl_runewords.h").write_text(text, encoding="utf-8")
    print(msg)
    return 0


if __name__ == "__main__":
    sys.exit(main())
