"""Median's unique carry limits (D2Sigma's `uniqueitems2`) as compiled-in plugin data (docs/subsystems/items-xp.md):

  plugin/src/mxl_unique_limits.h  one row per limited unique: LimitGroup, LimitCount, PickDuplicates

D2Sigma's table is parallel to uniqueitems.txt (row = unique index); work/sigma/uniqueitems2.txt comes from
sigma_tables.py decode. Rows with all three fields 0 carry no limit and are left out. The row count of the table must
equal the data rows of the built uniqueitems.txt, because the plugin looks a unique up by D2R's unique index, which is the
row of that file.

Usage: python tools/unique_limits_data.py   (after sigma_tables.py decode and txt_migrate.py; build.py runs it after items_data.py)
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SIGMA = ROOT / "work" / "sigma" / "uniqueitems2.txt"
BUILT = ROOT / "work" / "mod" / "data" / "global" / "excel" / "uniqueitems.txt"
OUT = ROOT / "plugin" / "src" / "mxl_unique_limits.h"
HEADER = "// Generated by tools/unique_limits_data.py; do not edit."


def rows(path: Path) -> list[list[str]]:
    lines = path.read_text("utf-8-sig").splitlines()
    return [ln.split("\t") for ln in lines[1:] if ln.strip()]


def main() -> int:
    sigma = rows(SIGMA)
    built = rows(BUILT)
    if len(sigma) != len(built):
        raise SystemExit(f"uniqueitems2 has {len(sigma)} rows, the built uniqueitems.txt has {len(built)}; "
                         "the unique index cannot be the row")
    out = []
    names = 0
    for i, r in enumerate(sigma):
        if int(r[0]) != i:
            raise SystemExit(f"uniqueitems2 row {i} is numbered {r[0]}")
        group, count, dup = int(r[2]), int(r[3]), int(r[4])
        if group == 0 and count == 0 and dup == 0:
            continue
        if not (-32768 <= group <= 32767 and 0 <= count <= 255 and 0 <= dup <= 255):
            raise SystemExit(f"uniqueitems2 row {i}: {group} {count} {dup} does not fit int16 / uint8 / uint8")
        out.append((i, group, count, dup, r[1]))
        if built[i][0].removeprefix("medianxl:") != r[1]:
            names += 1
    lines = [HEADER, "#pragma once", "", "#include <cstdint>", "", "namespace mxl_unique_limits {", "",
             "// D2Sigma's uniqueitems2 (D2Units 0x100bd060 / 0x100bd0b0): the carry limit of a unique, by its row in",
             "// uniqueitems.txt (= D2R's unique index). group 0: the limit counts copies of this unique; group n: it counts",
             "// every unique of group n. count: how many may be in the backpack. duplicates: 0 = a unique of a group may not",
             "// be picked up while a copy of the same unique is already there. Rows are sorted by row; rows not listed",
             "// have no limit.",
             "struct Row {", "\tint16_t row;", "\tint16_t group;", "\tuint8_t count;", "\tuint8_t duplicates;", "};",
             f"inline constexpr int32_t TableRows = {len(sigma)};  // rows of uniqueitems2 = data rows of uniqueitems.txt",
             f"inline constexpr int32_t RowCount = {len(out)};",
             "inline constexpr Row Rows[RowCount] = {"]
    for i, group, count, dup, name in out:
        lines.append(f"    {{{i}, {group}, {count}, {dup}}},  // {name}")
    lines += ["};", "", "}  // namespace mxl_unique_limits", ""]
    OUT.write_text("\n".join(lines), "utf-8", newline="\n")
    groups = {g for _, g, _, _, _ in out if g}
    print(f"   unique limits: {len(out)} of {len(sigma)} uniques limited ({len(groups)} groups) -> plugin/src/mxl_unique_limits.h"
          + (f"; {names} names differ from the built file (renamed rows, row order is what counts)" if names else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
