"""Resolve Median's layered item description string IDs to localization keys.

Descfunc 31/34 read the property parameter (stat layer), not descstrpos.
Only IDs actually referenced by Median's property slots are compiled into the plugin.
Run after tbl2json / txt_migrate; never substitute D2R numeric IDs into saved layers.
"""
import json
from pathlib import Path

import tbl2json
import txt_migrate as tm

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "assets" / "median" / "2_txt"


def references():
    h, rows = tm.read_tsv(DATA / "itemstatcost.txt")
    stats = {r[0] for r in rows if tm.is_record(r) and r[h.index("descfunc")] in ("31", "34")}
    h, rows = tm.read_tsv(DATA / "properties.txt")
    props = {r[0] for r in rows if tm.is_record(r) and any(r[h.index(f"stat{i}")] in stats for i in range(1, 8))}
    refs = []
    for path in sorted(DATA.glob("*.txt")):
        h, rows = tm.read_tsv(path)
        columns = tm.Migrator.property_columns(h)
        for index, r in enumerate(rows):
            if not tm.is_record(r):
                continue
            for code, param, low, high in columns:
                if r[code] not in props:
                    continue
                if param is None or not r[param].isdigit():
                    raise ValueError(f"{path.name} {r[0]}: layered text without a string ID")
                refs.append((path.stem, index, r[0], int(r[param]), r[low] if low is not None else ""))
    return refs


def main():
    ids = json.loads((tm.OUT / "strings_idkeys.json").read_text("utf-8"))
    originals, _ = tbl2json.load_median()
    texts = tm.strings_ns.effective_texts()
    entries = []
    for sid in sorted({r[3] for r in references()}):
        key = ids[str(sid)]
        # A native key may retain D2R's placeholders; its _mxl alias holds Median's text.
        bare = key.split(":", 1)[-1]
        if bare + "_mxl" in texts:
            key, bare = "medianxl:" + bare + "_mxl", bare + "_mxl"
        if texts.get(bare) != originals[sid][1]:
            raise ValueError(f"{sid}: {key} does not preserve Median's text")
        if ":" not in key:
            key = "d2r:" + key
        entries.append(f"\t{{{sid}, {json.dumps(key)}}},")
    h, rows = tm.read_tsv(ROOT / "work" / "sigma" / "skills2.txt")
    skill_ids = {e["row"]: e["id"] for e in json.loads((ROOT / "work" / "named" / "idmap.json").read_text("utf-8"))["skills"]}
    hidden = sorted(skill_ids[int(r[h.index("*row")])] for r in rows if tm.is_record(r) and r[h.index("AltTooltip")] == "1")
    lines = ["// Generated by tools/item_special_data.py; do not edit.", "#pragma once", "#include <cstdint>",
             "namespace mxl_special_text {", "struct Entry { uint16_t id; const char* key; };",
             "inline constexpr Entry Entries[] = {", *entries, "};",
             "// skills2 AltTooltip: Sigma omits the ordinary +skill line; a layered description explains the passive.",
             "inline constexpr int32_t AltTooltipSkills[] = {" + ", ".join(map(str, hidden)) + "};",
             "}  // namespace mxl_special_text", ""]
    (ROOT / "plugin" / "src" / "mxl_special_text.h").write_text("\n".join(lines), encoding="utf-8")
    print(f"layered item text: {len(entries)} Median IDs -> localization keys")


if __name__ == "__main__":
    main()
