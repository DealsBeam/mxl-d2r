"""D2Sigma's buff / debuff icon bar as plugin data (plugin/src/mxl_state_icons.h, mxl_state_icon_art.h).

D2Sigma draws the bar in ui/BottomPanel.cpp (functions 0x100d28e0 left group, 0x100d34b0 right group, one icon each
0x100d1230; docs/subsystems/buff-icons.md). Its source table is `stateicons` (236 rows x 8 bytes, research/sigma_schema.json):
i16 state (a Median states row, -1 = none), u8 side (0 left group, 1 right group), u8 tint, u16 frame in
game\\skills\\state-icons.dc6 (28 x 28 pixels, 202 frames), u16 tooltip string id (5382 = Median's "dummy", no tooltip).

  mxl_state_icons.h       committed: one row per state that has an icon: the migrated state id (work/named/idmap.json), side,
                          tint, frame (an index into the art header) and the tooltip's full string key (`medianxl:<key>` or
                          `d2r:<key>`, resolved through the plugin's localization service, tools/strings_ns.py)
  mxl_state_icon_art.h    NOT committed (.gitignore, Median's art): the referenced frames decoded with the skill icons' method
                          (tools/skill_icons.py read_dc6 / palette), 28 x 28 palette indices each (0 = transparent) and the
                          palette. The OverlayService draws rectangles, lines and text only, so the plugin turns the pixels
                          into rectangles at run time (plugin/src/buff_icons.cpp); the tint is applied there.

Usage: python tools/state_icons.py   (build.py runs it after tbl2json and the idmap)
"""
import json
import struct
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import skill_icons  # noqa: E402  (read_dc6, palette, SHEETS)

ROOT = Path(__file__).resolve().parent.parent
BIN = ROOT / "extract" / "mxl" / "data" / "global" / "excel" / "stateicons.bin"
IDMAP = ROOT / "work" / "named" / "idmap.json"
IDKEYS = ROOT / "work" / "mod" / "strings_idkeys.json"
OUT = ROOT / "plugin" / "src"
NO_STRING = 5382
NAMESPACE = "medianxl"
SIZE = 28
HEADER = "// Generated by tools/state_icons.py; do not edit."


def rows() -> list[tuple[int, int, int, int, int]]:
    b = BIN.read_bytes()
    n = struct.unpack_from("<I", b)[0]
    if len(b) != 4 + 8 * n:
        raise SystemExit(f"stateicons.bin: {len(b)} bytes is not {n} rows of 8")
    return [struct.unpack_from("<hBBHH", b, 4 + 8 * i) for i in range(n)]


def tooltip_key(string_id: int, idkeys: dict[str, str]) -> str:
    """The full key of a tooltip string, "" for none (the dummy placeholder, 5382)."""
    if string_id == NO_STRING:
        return ""
    key = idkeys.get(str(string_id))
    if key is None:
        raise SystemExit(f"tooltip string {string_id} has no key in {IDKEYS}; run tools/tbl2json.py first")
    return key if key.startswith(NAMESPACE + ":") else "d2r:" + key


def main() -> int:
    idmap = {e["row"]: e["id"] for e in json.loads(IDMAP.read_text("utf-8"))["states"]}
    idkeys = json.loads(IDKEYS.read_text("utf-8"))
    frames = skill_icons.read_dc6(skill_icons.SHEETS / "state-icons.dc6")
    palette = skill_icons.palette()
    used: list[int] = []
    table = []
    for i, (state, side, tint, frame, tip) in enumerate(rows()):
        if state == -1:
            continue  # D2Sigma skips these rows (`*psVar4 != -1`)
        if state not in idmap:
            raise SystemExit(f"stateicons row {i}: state {state} is not in {IDMAP}")
        if frame >= len(frames):
            raise SystemExit(f"stateicons row {i}: frame {frame} of {len(frames)}")
        if (frames[frame][0], frames[frame][1]) != (SIZE, SIZE):
            raise SystemExit(f"state-icons frame {frame} is {frames[frame][0]}x{frames[frame][1]}, not {SIZE}x{SIZE}")
        if frame not in used:
            used.append(frame)
        table.append((idmap[state], side, tint, frame, tooltip_key(tip, idkeys)))
    used.sort()
    index = {f: n for n, f in enumerate(used)}

    out = [HEADER, "#pragma once", "", "#include <cstdint>", "", "namespace mxl_stateicons {", "",
           "// One row per state that shows an icon, in D2Sigma's table order (the order of the icons within a group).",
           "// state = the migrated D2R states row, side 0 = left group, 1 = right group, tint = text colour index 0-12",
           "// (0 = the icon as drawn), frame = index into mxl_state_icon_art.h, tooltip = full string key (empty = none).",
           "struct Row {", "\tint16_t state;", "\tuint8_t side;", "\tuint8_t tint;", "\tuint16_t frame;", "\tconst char* tooltip;", "};",
           f"inline constexpr int RowCount = {len(table)};", f"inline constexpr int FrameCount = {len(used)};",
           "inline constexpr Row Rows[RowCount] = {"]
    for state, side, tint, frame, key in table:
        out.append(f"    {{{state}, {side}, {tint}, {index[frame]}, {json.dumps(key)}}},")
    out += ["};", "", "}  // namespace mxl_stateicons", ""]
    (OUT / "mxl_state_icons.h").write_text("\n".join(out), encoding="utf-8")

    art = [HEADER, "// Median's art (game\\skills\\state-icons.dc6 frames): not committed (.gitignore).", "#pragma once", "",
           "#include <cstdint>", "", "namespace mxl_stateicons {", "",
           f"inline constexpr int FrameSize = {SIZE};",
           "// RGB of the 256 palette entries (D2R's units palette); entry 0 is transparent in the frames.",
           "inline constexpr uint8_t Palette[256][3] = {"]
    for r, g, b in palette:
        art.append(f"    {{{r}, {g}, {b}}},")
    art += ["};", "", f"// {len(used)} frames of {SIZE * SIZE} palette indices, top row first; frame n of the table is index n here.",
            f"inline constexpr uint8_t Pixels[{len(used)}][{SIZE * SIZE}] = {{"]
    for f in used:
        w, h, _ox, _oy, block = frames[f]
        art.append("    {" + ",".join(map(str, decode_indices(w, h, block))) + "},")
    art += ["};", "", "}  // namespace mxl_stateicons", ""]
    (OUT / "mxl_state_icon_art.h").write_text("\n".join(art), encoding="utf-8")
    print(f"state icons: {len(table)} rows ({sum(1 for t in table if t[1] == 0)} left, {sum(1 for t in table if t[1] == 1)} right), "
          f"{len(used)} frames, {sum(1 for t in table if t[4])} with a tooltip -> {OUT / 'mxl_state_icons.h'}")
    return 0


def decode_indices(w: int, h: int, block: bytes) -> list[int]:
    """Palette indices (0 = transparent) of a DC6 frame, top row first (same walk as skill_icons.decode_frame)."""
    rows_ = [[0] * w for _ in range(h)]
    x, y, i = 0, h - 1, 0
    while i < len(block) and y >= 0:
        b = block[i]
        i += 1
        if b == 0x80:
            x, y = 0, y - 1
        elif b & 0x80:
            x += b & 0x7F
        else:
            for c in block[i:i + b]:
                if 0 <= x < w:
                    rows_[y][x] = c
                x += 1
            i += b
    return [c for line in rows_ for c in line]


if __name__ == "__main__":
    sys.exit(main())
