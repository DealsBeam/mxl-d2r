"""Median's Soulstealer monsters: every monstats row whose DescStr text names the Soulstealer property
(mon_soulstealer, mon_panopticon, mon_zagraal, ...) -> plugin/src/mxl_soulstealer.h (D2R monster class ids).

Median's patch notes (sigma 1.1.0, 2.1.0, 2.8.0): Soulstealer bosses heal 10% of max life when they kill a player and not
when their minions do. Nothing in a table switches the heal on, the description text is the only marker, so the list is
read from it. Run: py -3 tools/soulstealer_data.py (needs work/named/idmap.json from a build)."""
import csv
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
TXT = ROOT / "assets" / "median" / "2_txt"
IDMAP = ROOT / "work" / "named" / "idmap.json"
OUT = ROOT / "plugin" / "src" / "mxl_soulstealer.h"
WORD = "soulstealer"


def strings() -> dict[str, str]:
    out: dict[str, str] = {}
    for name in ("string.txt", "expansionstring.txt", "patchstring.txt"):
        p = TXT / "strings" / name
        if p.exists():
            for line in p.read_text("utf-8", errors="replace").splitlines():
                key, _, text = line.partition("\t")
                if text:
                    out[key] = text
    return out


def main() -> int:
    idmap = json.loads(IDMAP.read_text("utf-8"))
    ids = {e["row"]: e["id"] for e in idmap["monstats"]}
    text = strings()
    rows = list(csv.reader(open(TXT / "monstats.txt", encoding="utf-8", errors="replace", newline=""), delimiter="\t"))
    desc = rows[0].index("DescStr")
    found = []
    for row, r in enumerate(rows[1:]):
        if len(r) > desc and WORD in text.get(r[desc], "").lower():
            found.append((ids[row], r[5] or r[0], r[desc]))
    found.sort()
    out = ["// Generated by tools/soulstealer_data.py; do not edit.", "#pragma once", "", "#include <cstdint>", "",
           "namespace mxl_soulstealer {", "",
           "// D2R monster class ids (ascending) whose monstats DescStr names the Soulstealer property: they heal 10% of max life",
           "// when they kill a player (docs/unported.md, audit DC5).",
           f"inline constexpr int32_t MonsterCount = {len(found)};", "inline constexpr int32_t Monsters[MonsterCount] = {"]
    out += [f"    {m},  // {n} ({d})" for m, n, d in found]
    out += ["};", "", "}  // namespace mxl_soulstealer", ""]
    OUT.write_text("\n".join(out), encoding="utf-8")
    print(f"soulstealer: {len(found)} monsters -> {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
