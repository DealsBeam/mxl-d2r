"""The stat names of the built itemstatcost.txt as compiled-in plugin data (the harness `item` / `equip` verbs take
`fireresist=155` as well as `39=155`):

  plugin/src/mxl_stat_names.h  Names[id] = the `Stat` cell of row id of work/mod/data/global/excel/itemstatcost.txt

The stat id is the row (D2R compiles the table by row and ignores the `*ID` comment column). A row whose `*ID` cell is not its
row number is left out (nullptr): the name would be a guess, so the harness refuses it and the number has to be used. Two rows
with one name stop the step.

Usage: python tools/stat_names_data.py [itemstatcost.txt]   (build.py runs it after txt_migrate.py)
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BUILT = ROOT / "work" / "mod" / "data" / "global" / "excel" / "itemstatcost.txt"
OUT = ROOT / "plugin" / "src" / "mxl_stat_names.h"
HEADER = "// Generated by tools/stat_names_data.py; do not edit."


def main() -> int:
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else BUILT
    lines = [ln.split("\t") for ln in src.read_text("utf-8-sig").splitlines() if ln.strip()]
    head = lines[0]
    name_col, id_col = head.index("Stat"), head.index("*ID")
    names: list[str | None] = []
    skipped = []
    seen: dict[str, int] = {}
    for i, r in enumerate(lines[1:]):
        name = r[name_col].strip()
        if r[id_col].strip() != str(i):
            skipped.append((i, name, r[id_col]))
            names.append(None)
            continue
        if not name or not all(c.isalnum() or c == "_" for c in name):
            raise SystemExit(f"itemstatcost row {i}: stat name '{name}' is not an identifier")
        if name.lower() in seen:
            raise SystemExit(f"itemstatcost rows {seen[name.lower()]} and {i} are both named {name}")
        seen[name.lower()] = i
        names.append(name)
    out = [HEADER, "#pragma once", "", "#include <cstdint>", "", "namespace mxl_stat_names {", "",
           "// The `Stat` cell of each row of the built itemstatcost.txt, by stat id (D2R's row). nullptr: the row's `*ID` cell",
           "// is not the row number, so the name is not trusted (use the number).",
           f"inline constexpr int32_t Count = {len(names)};",
           "inline constexpr const char* Names[Count] = {"]
    for i, n in enumerate(names):
        out.append(f'    {"nullptr" if n is None else chr(34) + n + chr(34)},  // {i}')
    out += ["};", "", "}  // namespace mxl_stat_names", ""]
    OUT.write_text("\n".join(out), "utf-8", newline="\n")
    print(f"{len(names)} stat names -> {OUT.relative_to(ROOT)}; skipped (*ID is not the row): {skipped or 'none'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
