"""Our item type ids of the types D2R's code names by number (bugs #49 / #50 / #55): plugin/src/mxl_item_type_ids.h.

D2R.exe compares items against fixed type ids (the "item is of type" call 0x373890 with an immediate: 75 rune, 77 hpot,
...). D2R 3.x has a type `warl` at id 67 that 1.13 / Median lacks; until 0.69.16 our table appended it at the end, so every
type from `h2h` on was one id lower than D2R's (its rune was our circlet: the circlet crash #49 / #55, and runes applied
no socket mods, #50). txt_migrate (align_item_types) now puts D2R's own rows at D2R's numbers, so these ids must equal
D2R's: this tool fails the build when one does not, and the plugin part item_type_ids.cpp checks the same at start
(no patch). Ids are looked up by code in the built itemtypes.txt, whose data row (no `Expansion` row) is the type id.

Usage: python tools/item_type_ids.py   (after txt_migrate.py; build.py runs it)
"""
import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TABLE = ROOT / "work" / "mod" / "data" / "global" / "excel" / "itemtypes.txt"
D2R_TABLE = ROOT / "extract" / "d2r" / "93847" / "data" / "global" / "excel" / "itemtypes.txt"
OUT = ROOT / "plugin" / "src" / "mxl_item_type_ids.h"
# The types D2R.exe 93847 compares by a fixed id (plugin/src/item_type_ids.cpp lists the sites).
CODES = ["h2h", "pelt", "rune", "hpot", "apot", "wpot", "scha", "mcha", "gem4"]


def type_ids(path: Path) -> dict[str, int]:
    """Code -> type id: the data row index (an `Expansion` row is not a record)."""
    with path.open(encoding="utf-8-sig", errors="replace", newline="") as f:
        rows = list(csv.DictReader(f, delimiter="\t"))
    rows = [r for r in rows if (r.get("ItemType") or "").lower() != "expansion"]
    return {r["Code"]: i for i, r in enumerate(rows) if r.get("Code")}


def main() -> int:
    ids = type_ids(TABLE)
    missing = [c for c in CODES if c not in ids]
    if missing:
        print(f"item type ids: {missing} not in {TABLE}")
        return 1
    if D2R_TABLE.exists():
        d2r = type_ids(D2R_TABLE)
        wrong = [f"{c} ours {ids[c]}, D2R {d2r.get(c)}" for c in CODES if ids[c] != d2r.get(c)]
        if wrong:
            print("item type ids differ from D2R's fixed ids (txt_migrate align_item_types): " + "; ".join(wrong))
            return 1
    lines = ["// Generated by tools/item_type_ids.py; do not edit.",
             "// Our item type id (built itemtypes.txt) of each type D2R.exe compares by a fixed id; item_type_ids.cpp checks they match.",
             "#pragma once", "", "namespace mxl_item_type_ids {", "",
             "struct TypeId {", "\tconst char* code;", "\tint id;", "};", "",
             "constexpr TypeId Median[] = {"]
    lines += [f'\t{{"{c}", {ids[c]}}},' for c in CODES]
    lines += ["};", "", "}  // namespace mxl_item_type_ids", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print("item type ids: " + ", ".join(f"{c} {ids[c]}" for c in CODES) + f" -> {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
