"""Median's item type ids of the types D2R's code names by number (bug #49): plugin/src/mxl_item_type_ids.h.

D2R 3.x inserted a type `warl` at id 67 of itemtypes.txt (and has `none` at 1); Median keeps 1.13's layout, so every
type from `h2h` on is one id lower in our tables than in D2R's. D2R.exe compares items against fixed type ids (the "item
is of type" call 0x373890 with an immediate): 75 is D2R's rune, but our 75 is the circlet, so D2R handled every circlet
as a rune (the socket-filler branch of 0x475140 asserts `UnitGetType(hUnit) == UNIT_ITEM`, ItemMode.cpp:676, and the
game crashed when a circlet was picked up or worn). The plugin part item_type_ids.cpp rewrites those immediates to the
ids below (looked up by code in the built itemtypes.txt, whose row - 1 is the type id; see tools/game_checks.py
`typeids`).

Usage: python tools/item_type_ids.py   (after txt_migrate.py; build.py runs it)
"""
import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TABLE = ROOT / "work" / "mod" / "data" / "global" / "excel" / "itemtypes.txt"
OUT = ROOT / "plugin" / "src" / "mxl_item_type_ids.h"
# The types D2R.exe 93847 compares by a fixed id (plugin/src/item_type_ids.cpp lists the sites).
CODES = ["h2h", "pelt", "rune", "hpot", "apot", "wpot", "scha", "mcha", "gem4"]


def type_ids(path: Path) -> dict[str, int]:
    """Code -> type id: the data row index (an `Expansion` row is not a record)."""
    with path.open(encoding="utf-8-sig", errors="replace", newline="") as f:
        rows = list(csv.DictReader(f, delimiter="\t"))
    rows = [r for r in rows if (r.get("ItemType") or "").lower() != "expansion"]
    return {r["Code"]: i for i, r in enumerate(rows) if r.get("Code")}


def main() -> int:
    ids = type_ids(TABLE)
    missing = [c for c in CODES if c not in ids]
    if missing:
        print(f"item type ids: {missing} not in {TABLE}")
        return 1
    lines = ["// Generated by tools/item_type_ids.py; do not edit.",
             "// Median's item type id (built itemtypes.txt) of each type D2R.exe compares by a fixed id (item_type_ids.cpp).",
             "#pragma once", "", "namespace mxl_item_type_ids {", "",
             "struct TypeId {", "\tconst char* code;", "\tint id;", "};", "",
             "constexpr TypeId Median[] = {"]
    lines += [f'\t{{"{c}", {ids[c]}}},' for c in CODES]
    lines += ["};", "", "}  // namespace mxl_item_type_ids", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print("item type ids: " + ", ".join(f"{c} {ids[c]}" for c in CODES) + f" -> {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
