"""D2Sigma's NPC service flags and requirement rows as compiled-in plugin data (plugin/src/mxl_npc_services.h).

Source: extract/mxl npcext.bin (49 rows x 336 bytes; layout in docs/subsystems/npc-hirelings.md section 1.2):
  +0x00 monstats id, +0x04 flags (bit 0 shop, bit 1 gamble, bit 2 hirer), +0x0c / +0x10 / +0x14 requirement row that
  gates bit 0 / 1 / 2 (-1 or 0 = none). The NPC class goes through work/named/idmap.json like npc_actions_data.py.
Only the rows with at least one of bits 0-2 set, or with a requirement, are kept: plugin/src/requirement_gates.cpp
compares them with D2R's static NPC table (RVA 0x237ea60).

Usage: python tools/npc_services_data.py [--root <repo with extract/ and work/>]
"""
import argparse
import json
import struct
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
NPC_ROW = 336
HEADER = "// Generated by tools/npc_services_data.py; do not edit."


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", type=Path, default=REPO, help="repo root holding extract/ and work/ (default: this checkout)")
    ap.add_argument("--out", type=Path, default=REPO / "plugin" / "src" / "mxl_npc_services.h")
    args = ap.parse_args()
    bins = args.root / "extract" / "mxl" / "data" / "global" / "excel"
    idmap = json.loads((args.root / "work" / "named" / "idmap.json").read_text("utf-8"))
    mon = {e["row"]: e["id"] for e in idmap["monstats"]}
    b = (bins / "npcext.bin").read_bytes()
    n = struct.unpack_from("<I", b)[0]
    if len(b) != 4 + n * NPC_ROW:
        raise SystemExit(f"npcext.bin: {len(b)} bytes is not {n} rows of {NPC_ROW}")
    rows = []
    for i in range(n):
        r = b[4 + i * NPC_ROW:4 + (i + 1) * NPC_ROW]
        cls, flags, _a, shop, gamble, hire = struct.unpack_from("<6i", r, 0)
        if cls not in mon:
            raise SystemExit(f"npcext row {i}: monster {cls} is not in work/named/idmap.json")
        if flags & 7 == 0 and max(shop, gamble, hire) <= 0:
            continue
        rows.append((mon[cls], flags & 7, shop, gamble, hire))
    out = [HEADER, "#pragma once", "", "#include <cstdint>", "", "namespace mxl_npc {", "",
           "// D2Sigma's npcext service flags (bit 0 shop, bit 1 gamble, bit 2 hirer) and the requirement rows",
           "// (mxl_requirements.h; -1 = none) that gate them. cls is the D2R monster id of the NPC.",
           "struct Service {", "\tuint16_t cls;", "\tuint8_t flags;", "\tint32_t shop;", "\tint32_t gamble;", "\tint32_t hire;", "};",
           f"inline constexpr int32_t ServiceCount = {len(rows)};", "inline constexpr Service Services[ServiceCount] = {"]
    for cls, flags, shop, gamble, hire in rows:
        out.append(f"    {{{cls}, {flags}, {shop}, {gamble}, {hire}}},")
    out += ["};", "", "}  // namespace mxl_npc", ""]
    args.out.write_text("\n".join(out), encoding="utf-8")
    print(f"npc services: {len(rows)} NPCs -> {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
