"""Median's infographic help panels as D2R panel layouts (plugin/src/mxl_infographics.h; docs/unported.md).

Median's server asks the client to open a help panel when the player right clicks an item with an infographic (misc2
`Infographic`, item event 13, packet 0x16; the catalyst of disenchantment is the only one). The panel is a picture with a
title and positioned text blocks (infographics.txt: text key, font, colour, x, y). No art of it exists in D2R, so each
infographic becomes a text panel on the stock modal frame: the title and the blocks in two columns, in the order of
the picture (top to bottom). Median draws the lines of a block from the bottom up (the strings read "to obtain Arcane
Shards / with unique items in the Horadric Cube / Transmute the Catalyst of Disenchantment"), so the lines of a block are
shown in reverse order, which reads as the steps of the picture.
"""
from __future__ import annotations

import json

PLUGIN_ID = "mxl-core"
FRAME = "Panel\\Modals\\Modal_No_Title_BG"   # the stock modal frame the SDK sample uses (1254 x 540 at -627, -270)
COLUMN_X = (78, 646)
COLUMN_WIDTH = 530
TOP = 150
LINE = 34       # pixels per text line (the modal description style)
GAP = 30        # between two blocks of a column
HINT = "ÿc5Press Escape to close."


def reading_lines(text: str) -> list[str]:
    """The lines of one block in reading order (Median stores them bottom up)."""
    return [line for line in text.strip("\n").split("\n")][::-1]


def layout(local_id: str, title: str, blocks: list[tuple[int, str]]) -> dict:
    """The panel layout JSON as a dict. `blocks`: (y in Median's picture, text) per block."""
    ordered = [text for _y, text in sorted(blocks, key=lambda b: b[0])]
    half = (len(ordered) + 1) // 2
    widgets = [{"type": "TextBoxWidget", "name": "Title",
                "fields": {"rect": {"x": 78, "y": 60, "width": 1076, "height": 70}, "text": title, "style": "$StyleSettingsTitle"}}]
    n = 0
    for column, group in enumerate((ordered[:half], ordered[half:])):
        y = TOP
        for text in group:
            lines = reading_lines(text)
            n += 1
            widgets.append({"type": "TextBoxWidget", "name": "Block%d" % n,
                            "fields": {"rect": {"x": COLUMN_X[column], "y": y, "width": COLUMN_WIDTH, "height": LINE * len(lines)},
                                       "text": "\n".join(lines), "style": "$StyleModalDialogDescription"}})
            y += LINE * len(lines) + GAP
    widgets.append({"type": "TextBoxWidget", "name": "Hint",
                    "fields": {"rect": {"x": 78, "y": 470, "width": 1076, "height": 40}, "text": HINT,
                               "style": "$StyleModalDialogDescription"}})
    return {"type": "Panel", "name": "%s/%s" % (PLUGIN_ID, local_id),
            "fields": {"anchor": {"x": 0.5, "y": 0.5}, "priority": 8500},
            "children": [{"type": "ImageWidget", "name": "Frame",
                          "fields": {"rect": {"x": -627, "y": -270}, "filename": FRAME}, "children": widgets}]}


def c_literal_lines(text: str) -> list[str]:
    """`text` (one JSON document, several lines) as C string literals, one per line; non-ASCII as octal escapes of the
    UTF-8 bytes (the colour code 0xC3 0xBF must not run into a following hex digit)."""
    out = []
    for line in text.split("\n"):
        pieces = []
        for b in (line + "\n").encode("utf-8"):
            ch = chr(b)
            if ch == "\n":
                pieces.append("\\n")
            elif ch in '\\"':
                pieces.append("\\" + ch)
            elif 0x20 <= b < 0x7F:
                pieces.append(ch)
            else:
                pieces.append("\\%03o" % b)
        out.append('    "' + "".join(pieces) + '"')
    return out


def header(panels: list[tuple[str, dict]], items: list[tuple[str, int]]) -> str:
    """plugin/src/mxl_infographics.h. `panels`: (local id, layout); `items`: (item code as a 4 char string, panel index)."""
    lines = ["// Generated by tools/txt_migrate.py (infographic_panels, from infographics.txt via tools/infographics.py); do not edit.",
             "#pragma once", "", "#include <cstdint>", "", "namespace mxl_infographics {", "",
             "// Median's help panels (misc2 Infographic) as D2R panel layouts: local panel id, layout JSON",
             "// (data/global/ui/layouts/mxl-core/<local id>hd.json).",
             "struct Panel {", "\tconst char* localId;", "\tconst char* layout;", "};"]
    for i, (local_id, doc) in enumerate(panels):
        lines.append("inline constexpr char Layout%d[] =" % i)
        lines += c_literal_lines(json.dumps(doc, indent=1, ensure_ascii=False))
        lines[-1] += ";"
    lines += ["inline constexpr Panel Panels[] = {"]
    lines += ['    {"%s", Layout%d},' % (local_id, i) for i, (local_id, _doc) in enumerate(panels)]
    lines += ["};", f"inline constexpr int32_t PanelCount = {len(panels)};", "",
              "// Items whose right click opens one of them: item code (4 chars, little-endian), index into Panels.",
              "struct Item {", "\tuint32_t code;", "\tint32_t panel;", "};", "inline constexpr Item Items[] = {"]
    for code, panel in items:
        word = int.from_bytes((code + "    ")[:4].encode("latin1"), "little")
        lines.append('    {0x%08x, %d},  // "%s"' % (word, panel, code))
    lines += ["};", "", "}  // namespace mxl_infographics", ""]
    return "\n".join(lines)
